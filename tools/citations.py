def pin(checkout: Path) -> dict[str, dict]:
    out, problems = {}, []
    for key, path, needle, span in CITES:
        f = checkout / path
        if not f.is_file():
            problems.append(f"{key}: missing file {path}")
            continue
        lines = f.read_text(encoding="utf-8").splitlines()
        start = next((i for i, ln in enumerate(lines, 1) if needle in ln), None)
        if start is None:
            problems.append(f"{key}: needle not found in {path}: {needle!r}")
            continue
        end = min(len(lines), start + span - 1)
        out[key] = {"path": path, "start": start, "end": end, "needle": needle}
    if problems:
        sys.exit("\n".join(["PIN FAILED"] + problems))
    return out


def url(c: dict) -> str:
    frag = f"#L{c['start']}" + (f"-L{c['end']}" if c["end"] != c["start"] else "")
    return BASE + c["path"] + frag


def targets() -> list[Path]:
    return [ROOT / "README.md", *sorted((ROOT / "book").glob("*.md")), *sorted((ROOT / "appendix").glob("*.md")),
            ROOT / "labs" / "README.md"]


def write_table(cites: dict[str, dict]) -> None:
    rows = ["# Citations (generated)", "",
            f"`tools/citations.py` આ table બનાવે છે. દરેક link pinned commit `{SHA[:7]}` પર છે; "
            "\"needle\" એ line range ની પહેલી line માં મળેલો શબ્દસમૂહ છે.", "",
            "| Key | File | Lines | Needle |", "|---|---|---|---|"]
    for key, c in cites.items():
        needle = c["needle"].strip().replace("|", "\\|").replace("`", "'")
        rows.append(f"| `{key}` | [{c['path']}]({url(c)}) | {c['start']}–{c['end']} | `{needle[:70]}` |")
    (ROOT / "appendix" / "citations.generated.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


def rewrite_refs(cites: dict[str, dict]) -> list[str]:
    problems = []
    for f in targets():
        if not f.exists() or f.name == "citations.generated.md":
            continue
        text = f.read_text(encoding="utf-8")
        body = text.split(START)[0].rstrip() + "\n"
        prose = re.sub(r"```.*?```", "", body, flags=re.S)
        used = sorted(set(re.findall(r"\]\[([a-z0-9-]+)\]", prose)))
        for key in used:
            if key not in cites:
                problems.append(f"{f.relative_to(ROOT)}: undefined citation [{key}]")
        if used:
            body += "\n" + START + "\n" + "\n".join(f"[{k}]: {url(cites[k])}" for k in used if k in cites) + "\n" + END + "\n"
        f.write_text(body, encoding="utf-8")
        for target in re.findall(r"\]\((?!https?:|#|mailto:)([^)\s]+)\)", prose):
            rel = target.split("#")[0]
            if rel and not (f.parent / rel).exists():
                problems.append(f"{f.relative_to(ROOT)}: broken relative link {target}")
    return problems


def main() -> None:
    if len(sys.argv) > 1:
        cites = pin(Path(sys.argv[1]))
        LOCK.write_text(json.dumps({"sha": SHA, "cites": cites}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    else:
        cites = json.loads(LOCK.read_text(encoding="utf-8"))["cites"]
    write_table(cites)
    problems = rewrite_refs(cites)
    if problems:
        sys.exit("\n".join(["VERIFY FAILED"] + problems))
    print(f"OK: {len(cites)} citations pinned to {SHA[:7]}; {len(targets())} files checked.")


if __name__ == "__main__":
    main()
